'use client';

import React, { useState, useRef, useMemo, useCallback } from 'react';
import { useRouter } from 'next/navigation';
import { api } from '../../lib/api';
import StatusBadge from '../../components/StatusBadge';
import Toast from '../../components/Toast';

// ---------------------------------------------------------------------------
// SequenceModal — inline modal, no external library
// ---------------------------------------------------------------------------
function SequenceModal({ count, onSubmit, onCancel, submitting }) {
  const touchesRef = useRef(null);
  const spacingRef = useRef(null);

  const handleSubmit = (e) => {
    e.preventDefault();
    const touches = parseInt(touchesRef.current.value, 10);
    const spacing = parseInt(spacingRef.current.value, 10);
    // Build the intervals array: e.g. 3 touches @ 3 days → [3, 6, 9]
    const intervals = Array.from({ length: touches }, (_, i) => spacing * (i + 1));
    onSubmit({ intervals });
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center">
      {/* Backdrop */}
      <div
        className="absolute inset-0 bg-black/40"
        onClick={onCancel}
        aria-hidden="true"
      />
      {/* Card */}
      <div className="relative z-10 bg-white rounded-xl shadow-xl w-full max-w-md mx-4 p-6">
        <h2 className="text-base font-semibold text-gray-900 mb-1">
          Schedule follow-up sequence
        </h2>
        <p className="text-sm text-gray-500 mb-5">
          Scheduling for <span className="font-medium text-gray-700">{count}</span> selected proposal{count !== 1 ? 's' : ''}.
          Messages will be auto-generated by AI.
        </p>

        <form onSubmit={handleSubmit} className="space-y-4">
          <div>
            <label className="label" htmlFor="seq-touches">
              Number of touches
              <span className="ml-1 text-gray-400 font-normal normal-case">(2 – 5)</span>
            </label>
            <input
              id="seq-touches"
              ref={touchesRef}
              type="number"
              defaultValue={3}
              min={2}
              max={5}
              required
              className="input py-1.5 bg-white"
            />
          </div>

          <div>
            <label className="label" htmlFor="seq-spacing">
              Days between touches
              <span className="ml-1 text-gray-400 font-normal normal-case">(1 – 14)</span>
            </label>
            <input
              id="seq-spacing"
              ref={spacingRef}
              type="number"
              defaultValue={3}
              min={1}
              max={14}
              required
              className="input py-1.5 bg-white"
            />
            <p className="mt-1 text-xs text-gray-400">
              e.g. 3 touches × 3 days → follow-ups at day 3, 6, 9
            </p>
          </div>

          <div className="flex justify-end gap-2 pt-2">
            <button
              type="button"
              onClick={onCancel}
              disabled={submitting}
              className="btn-secondary text-sm px-4 py-2"
            >
              Cancel
            </button>
            <button
              type="submit"
              disabled={submitting}
              className="bg-blue-600 hover:bg-blue-700 disabled:opacity-50 text-white text-sm font-medium px-4 py-2 rounded-md transition-colors"
            >
              {submitting ? 'Scheduling…' : 'Schedule'}
            </button>
          </div>
        </form>
      </div>
    </div>
  );
}

function LoomIcon() {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      fill="currentColor"
      className="w-4 h-4"
      aria-hidden="true"
    >
      <circle cx="12" cy="12" r="10" fill="#625DF5" />
      <polygon points="9,7.5 9,16.5 17,12" fill="white" />
    </svg>
  );
}

const STATUSES = ['all', 'sent', 'hired', 'rejected', 'pending', 'withdrawn'];
const PAGE_SIZE = 25;

export default function ProposalsClient({ initialProposals }) {
  const router = useRouter();
  const [proposals, setProposals] = useState(initialProposals);
  const [loadingMore, setLoadingMore] = useState(false);
  const [hasMore, setHasMore] = useState(initialProposals.length === PAGE_SIZE);
  const [filter, setFilter] = useState('all');
  const [search, setSearch] = useState('');
  const [expandedId, setExpandedId] = useState(null);
  const [details, setDetails] = useState({});
  const [toast, setToast] = useState(null);

  // Bulk follow-up scheduling
  const [selectedIds, setSelectedIds] = useState(new Set());
  const [sequenceModalOpen, setSequenceModalOpen] = useState(false);
  const [scheduling, setScheduling] = useState(false);

  function toggleSelected(id) {
    setSelectedIds((prev) => {
      const next = new Set(prev);
      if (next.has(id)) next.delete(id);
      else next.add(id);
      return next;
    });
  }

  function toggleSelectAll() {
    setSelectedIds((prev) =>
      prev.size === filtered.length && filtered.length > 0
        ? new Set()
        : new Set(filtered.map((p) => p.id))
    );
  }

  async function scheduleSequence({ intervals }) {
    if (selectedIds.size === 0) return;
    setScheduling(true);
    const ids = [...selectedIds];
    const results = await Promise.allSettled(
      ids.map((id) =>
        api.post('/follow-ups/sequence', {
          proposalId: id,
          intervals,
          autoGenerate: true,
        })
      )
    );
    const success = results.filter((r) => r.status === 'fulfilled').length;
    const failed = results.length - success;
    setScheduling(false);
    setSequenceModalOpen(false);
    setSelectedIds(new Set());
    if (failed === 0) {
      setToast({ message: `Scheduled ${success} sequence${success !== 1 ? 's' : ''}`, type: 'success' });
    } else {
      setToast({
        message: `Scheduled ${success} · ${failed} failed`,
        type: failed === results.length ? 'error' : 'success',
      });
    }
    router.refresh();
  }

  const loadMore = async () => {
    setLoadingMore(true);
    try {
      const data = await api.get(`/proposals?limit=${PAGE_SIZE}&offset=${proposals.length}&sort=created_at&order=desc`);
      const list = Array.isArray(data) ? data : [];
      setProposals((prev) => [...prev, ...list]);
      setHasMore(list.length === PAGE_SIZE);
    } catch {
      setToast({ message: 'Failed to load more proposals', type: 'error' });
    } finally {
      setLoadingMore(false);
    }
  };

  const filtered = useMemo(() => {
    return proposals.filter((p) => {
      if (filter !== 'all' && p.status !== filter) return false;
      if (search && !p.job_title?.toLowerCase().includes(search.toLowerCase())) return false;
      return true;
    });
  }, [proposals, filter, search]);

  const updateStatus = useCallback(async (id, status) => {
    try {
      await api.put(`/proposals/${id}`, { status });
      setProposals(prev => prev.map(p => p.id === id ? { ...p, status } : p));
    } catch (err) {
      setToast({ message: 'Failed to update status', type: 'error' });
    }
  }, []);

  const handleDelete = useCallback(async (id) => {
    if (!confirm('Delete this proposal? This cannot be undone.')) return;
    try {
      await api.del(`/proposals/${id}`);
      setProposals(prev => prev.filter(p => p.id !== id));
      setExpandedId(null);
    } catch (err) {
      setToast({ message: 'Failed to delete proposal', type: 'error' });
    }
  }, []);

  const handleEarningsUpdate = useCallback((id, earnings) => {
    api.put(`/proposals/${id}`, { earnings }).then((updated) => {
      setProposals(prev => prev.map(x => x.id === id ? updated : x));
    }).catch(() => setToast({ message: 'Failed to save earnings', type: 'error' }));
  }, []);

  const handleUpdate = useCallback((updated) => {
    setProposals(prev => prev.map(x => x.id === updated.id ? updated : x));
  }, []);

  const formatDate = useCallback((d) => {
    if (!d) return '—';
    return new Date(d).toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' });
  }, []);

  const formatBudget = useCallback((p) => {
    if (p.job_budget_amount) return `$${p.job_budget_amount} ${p.job_budget_type || ''}`;
    if (p.job_budget_min && p.job_budget_max) return `$${p.job_budget_min}-$${p.job_budget_max}`;
    return '—';
  }, []);

  return (
    <div className="page-container">
      <div className="page-header">
        <h1 className="page-title">Proposals</h1>
        <p className="page-subtitle">Track your sent proposals, win rates, and earnings</p>
      </div>

      {/* Bulk-action toolbar — only visible when at least one row is selected */}
      {selectedIds.size > 0 && (
        <div className="sticky top-0 z-10 bg-white border-b border-gray-200 py-2 px-4 flex items-center justify-between mb-2 rounded-lg shadow-sm">
          <span className="text-sm font-medium text-gray-700">
            {selectedIds.size} selected
          </span>
          <div className="flex gap-2">
            <button
              type="button"
              onClick={() => setSelectedIds(new Set())}
              className="text-sm text-gray-600 hover:text-gray-900"
            >
              Clear
            </button>
            <button
              type="button"
              onClick={() => setSequenceModalOpen(true)}
              className="bg-blue-600 hover:bg-blue-700 text-white text-sm font-medium px-3 py-1.5 rounded-md transition-colors"
            >
              Schedule follow-up sequence
            </button>
          </div>
        </div>
      )}

      <div className="flex gap-3 mb-4">
        <select
          value={filter}
          onChange={(e) => setFilter(e.target.value)}
          className="input bg-white"
        >
          {STATUSES.map(s => (
            <option key={s} value={s}>{s === 'all' ? 'All Statuses' : s.charAt(0).toUpperCase() + s.slice(1)}</option>
          ))}
        </select>
        <input
          type="text"
          value={search}
          onChange={(e) => setSearch(e.target.value)}
          placeholder="Search by job title..."
          className="flex-1 input"
        />
      </div>

      {filtered.length === 0 ? (
        <div className="card p-12 text-center text-gray-500">
          <p className="text-lg mb-2">No proposals yet</p>
          <p className="text-sm">Generate your first proposal from the Chrome extension.</p>
        </div>
      ) : (
        <div className="table-container">
          <div className="table-responsive">
          <table className="w-full text-sm">
            <thead>
              <tr className="bg-gray-50/60 border-b border-gray-200/60 text-left text-xs font-medium text-gray-500 uppercase tracking-wider">
                <th className="w-8 px-2 py-3">
                  {filtered.length > 0 && (
                    <input
                      type="checkbox"
                      aria-label="Select all proposals"
                      checked={selectedIds.size === filtered.length}
                      onChange={toggleSelectAll}
                      className="rounded border-gray-300 text-blue-600 focus:ring-blue-500 cursor-pointer"
                    />
                  )}
                </th>
                <th className="px-4 py-3">Date</th>
                <th className="px-4 py-3">Job Title</th>
                <th className="px-4 py-3">Location</th>
                <th className="px-4 py-3">Budget</th>
                <th className="px-4 py-3">Status</th>
                <th className="px-4 py-3">Rate</th>
                <th className="px-4 py-3">Loom</th>
              </tr>
            </thead>
            <tbody>
              {filtered.map((p) => (
                <Row
                  key={p.id}
                  proposal={{ ...p, ...(details[p.id] || {}) }}
                  expanded={expandedId === p.id}
                  selected={selectedIds.has(p.id)}
                  onSelect={() => toggleSelected(p.id)}
                  onToggle={async () => {
                    if (expandedId === p.id) { setExpandedId(null); return; }
                    if (!details[p.id]) {
                      try {
                        const full = await api.get(`/proposals/${p.id}`);
                        setDetails(prev => ({ ...prev, [p.id]: full }));
                      } catch { /* use list data as fallback */ }
                    }
                    setExpandedId(p.id);
                  }}
                  onStatusChange={updateStatus}
                  onDelete={handleDelete}
                  onEarningsUpdate={handleEarningsUpdate}
                  onUpdate={handleUpdate}
                  onToast={setToast}
                  formatDate={formatDate}
                  formatBudget={formatBudget}
                />
              ))}
            </tbody>
          </table>
          </div>
          {hasMore && (
            <div className="flex justify-center py-4 border-t border-gray-100">
              <button
                type="button"
                onClick={loadMore}
                disabled={loadingMore}
                className="btn-secondary text-xs px-4 py-2"
              >
                {loadingMore ? 'Loading...' : 'Load more'}
              </button>
            </div>
          )}
        </div>
      )}
      {sequenceModalOpen && (
        <SequenceModal
          count={selectedIds.size}
          onSubmit={scheduleSequence}
          onCancel={() => setSequenceModalOpen(false)}
          submitting={scheduling}
        />
      )}

      {toast && <Toast message={toast.message} type={toast.type} onClose={() => setToast(null)} />}
    </div>
  );
}

const RESPONSE_TYPE_COLORS = {
  interview: 'badge-blue',
  hired: 'badge-purple',
  rejected: 'bg-red-100 text-red-700 text-xs font-medium px-2 py-0.5 rounded-full',
  no_response: 'bg-gray-100 text-gray-500 text-xs font-medium px-2 py-0.5 rounded-full',
};

const today = () => new Date().toISOString().split('T')[0];

const Row = React.memo(function Row({ proposal, expanded, selected, onSelect, onToggle, onStatusChange, onDelete, onEarningsUpdate, onUpdate, onToast, formatDate, formatBudget }) {
  const p = proposal;

  const [responseType, setResponseType] = useState(p.response_type || '');
  const [respondedAt, setRespondedAt] = useState(p.responded_at ? p.responded_at.split('T')[0] : today());
  const [declineReason, setDeclineReason] = useState(p.decline_reason || '');
  const [clientFeedback, setClientFeedback] = useState(p.client_feedback || '');
  const [savingOutcome, setSavingOutcome] = useState(false);
  const [savingLoom, setSavingLoom] = useState(false);

  const saveOutcome = async (e) => {
    e.stopPropagation();
    setSavingOutcome(true);
    try {
      const updated = await api.put(`/proposals/${p.id}`, {
        response_type: responseType || null,
        responded_at: respondedAt || null,
        decline_reason: responseType === 'rejected' ? declineReason : null,
        client_feedback: clientFeedback || null,
      });
      onUpdate(updated);
    } catch {
      if (onToast) onToast({ message: 'Failed to save outcome', type: 'error' });
    } finally {
      setSavingOutcome(false);
    }
  };

  const editLoom = async (e) => {
    e.stopPropagation();
    const current = p.loom_url || '';
    // prompt() is intentional for v0 — lightweight, no modal component needed
    const input = prompt('Paste Loom share URL (leave empty to remove):', current);
    if (input === null) return; // cancelled
    const loomUrl = input.trim() || null;
    setSavingLoom(true);
    try {
      const updated = await api.patch(`/proposals/${p.id}`, { loomUrl });
      onUpdate(updated);
    } catch {
      if (onToast) onToast({ message: 'Failed to save Loom URL', type: 'error' });
    } finally {
      setSavingLoom(false);
    }
  };

  return (
    <>
      <tr onClick={onToggle} className="cursor-pointer">
        <td className="w-8 px-2 py-3" onClick={(e) => e.stopPropagation()}>
          <input
            type="checkbox"
            aria-label={`Select proposal ${p.job_title || p.id}`}
            checked={selected}
            onChange={onSelect}
            className="rounded border-gray-300 text-blue-600 focus:ring-blue-500 cursor-pointer"
          />
        </td>
        <td className="px-4 py-3 text-gray-500 whitespace-nowrap">{formatDate(p.created_at)}</td>
        <td className="px-4 py-3 font-medium text-gray-900 max-w-xs truncate">
          {p.job_title || '—'}
          {p.connect_cost && <span className="text-xs text-gray-400 ml-2">{p.connect_cost}C</span>}
        </td>
        <td className="px-4 py-3 text-gray-500">{p.client_location || '—'}</td>
        <td className="px-4 py-3 text-gray-500 whitespace-nowrap">{formatBudget(p)}</td>
        <td className="px-4 py-3">
          <div className="flex items-center gap-1.5 flex-wrap">
            <StatusBadge status={p.status} />
            {p.response_type && (
              <span className={RESPONSE_TYPE_COLORS[p.response_type] || 'badge-blue'}>
                {p.response_type.replace('_', ' ')}
              </span>
            )}
          </div>
        </td>
        <td className="px-4 py-3 text-gray-500 whitespace-nowrap">{p.hourly_rate ? `$${p.hourly_rate}` : '—'}</td>
        <td className="px-4 py-3 text-center">
          {p.loom_url ? (
            <a
              href={p.loom_url}
              target="_blank"
              rel="noopener noreferrer"
              title="Watch Loom video"
              onClick={(e) => e.stopPropagation()}
              className="inline-flex items-center justify-center text-indigo-500 hover:text-indigo-700 transition-colors"
            >
              <LoomIcon />
              <span className="sr-only">Loom video</span>
            </a>
          ) : (
            <span className="text-gray-300">—</span>
          )}
        </td>
      </tr>
      {expanded && (
        <tr>
          <td colSpan={8} className="px-4 py-4 bg-gray-50/60 border-b border-gray-200/60">
            <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
              <div>
                <h4 className="text-xs font-medium text-gray-500 uppercase mb-2">Proposal</h4>
                <div className="text-sm text-gray-700 whitespace-pre-wrap bg-white/80 rounded-xl p-3 border border-gray-200/60 max-h-60 overflow-y-auto">
                  {p.proposal_text || 'No proposal text'}
                </div>
              </div>
              <div>
                <h4 className="text-xs font-medium text-gray-500 uppercase mb-2">Job Description</h4>
                <div className="text-sm text-gray-600 whitespace-pre-wrap bg-white/80 rounded-xl p-3 border border-gray-200/60 max-h-40 overflow-y-auto">
                  {p.job_description || 'No description'}
                </div>

                <h4 className="text-xs font-medium text-gray-500 uppercase mt-4 mb-2">Client Info</h4>
                <div className="text-sm text-gray-600 space-y-1">
                  <div>Location: <span className="text-gray-900">{p.client_location || '—'}</span></div>
                  <div>Total Spent: <span className="text-gray-900">{p.client_total_spent || '—'}</span></div>
                  <div>Hire Rate: <span className="text-gray-900">{p.client_hire_rate || '—'}</span></div>
                </div>

                <h4 className="text-xs font-medium text-gray-500 uppercase mt-4 mb-2">Update Status</h4>
                <select
                  value={p.status}
                  onChange={(e) => { e.stopPropagation(); onStatusChange(p.id, e.target.value); }}
                  className="input py-1.5 bg-white"
                >
                  {['sent', 'hired', 'rejected', 'pending', 'withdrawn'].map(s => (
                    <option key={s} value={s}>{s.charAt(0).toUpperCase() + s.slice(1)}</option>
                  ))}
                </select>

                <h4 className="text-xs font-medium text-gray-500 uppercase mt-4 mb-2">Outcome Tracking</h4>
                <div className="space-y-3" onClick={(e) => e.stopPropagation()}>
                  <div>
                    <label className="label">Response Type</label>
                    <select
                      value={responseType}
                      onChange={(e) => setResponseType(e.target.value)}
                      className="input py-1.5 bg-white"
                    >
                      <option value="">— Not set —</option>
                      <option value="interview">Interview</option>
                      <option value="hired">Hired</option>
                      <option value="rejected">Rejected</option>
                      <option value="no_response">No Response</option>
                    </select>
                  </div>

                  <div>
                    <label className="label">Responded At</label>
                    <input
                      type="date"
                      value={respondedAt}
                      onChange={(e) => setRespondedAt(e.target.value)}
                      className="input py-1.5 bg-white"
                    />
                  </div>

                  {responseType === 'rejected' && (
                    <div>
                      <label className="label">Decline Reason</label>
                      <input
                        type="text"
                        value={declineReason}
                        onChange={(e) => setDeclineReason(e.target.value)}
                        placeholder="e.g. Budget mismatch, went with another freelancer"
                        className="input py-1.5"
                      />
                    </div>
                  )}

                  <div>
                    <label className="label">Client Feedback <span className="text-gray-400 font-normal normal-case">(optional)</span></label>
                    <textarea
                      value={clientFeedback}
                      onChange={(e) => setClientFeedback(e.target.value)}
                      placeholder="Any feedback or notes from the client..."
                      rows={2}
                      className="input py-1.5 resize-none"
                    />
                  </div>

                  <button
                    onClick={saveOutcome}
                    disabled={savingOutcome}
                    className="btn-secondary text-xs px-3 py-1.5"
                  >
                    {savingOutcome ? 'Saving…' : 'Save Outcome'}
                  </button>
                </div>

                {p.connect_cost > 0 && (
                  <div className="mt-3 text-sm text-gray-500">
                    Connects: <span className="font-medium text-gray-700">{p.connect_cost}</span> (${(p.connect_cost * 0.3).toFixed(2)})
                  </div>
                )}

                {p.status === 'hired' && (
                  <div className="mt-4">
                    <h4 className="text-xs font-medium text-gray-500 uppercase mb-2">Earnings from this job</h4>
                    <div className="flex items-center gap-2">
                      <span className="text-gray-500">$</span>
                      <input
                        type="number"
                        defaultValue={p.earnings || ''}
                        placeholder="0.00"
                        onClick={(e) => e.stopPropagation()}
                        onBlur={(e) => {
                          const val = parseFloat(e.target.value);
                          if (val > 0 && val !== parseFloat(p.earnings)) onEarningsUpdate(p.id, val);
                        }}
                        className="w-32 input py-1"
                      />
                      {p.earnings > 0 && p.connect_cost > 0 && (
                        <span className="text-xs text-green-600 font-medium">
                          ROI: {(p.earnings / (p.connect_cost * 0.3)).toFixed(1)}x
                        </span>
                      )}
                    </div>
                  </div>
                )}
              </div>
            </div>
            <div className="flex items-center gap-4 mt-3 flex-wrap">
              {p.job_url && (
                <a href={p.job_url} target="_blank" rel="noopener noreferrer" className="inline-flex items-center gap-1 text-blue-600 text-sm font-medium hover:text-blue-700 hover:underline transition-colors">
                  View job on Upwork →
                </a>
              )}
              {p.loom_url && (
                <a href={p.loom_url} target="_blank" rel="noopener noreferrer" className="inline-flex items-center gap-1.5 text-indigo-600 text-sm font-medium hover:text-indigo-700 hover:underline transition-colors">
                  <LoomIcon />
                  Watch Loom →
                </a>
              )}
              <button
                onClick={editLoom}
                disabled={savingLoom}
                className="btn-secondary text-xs px-3 py-1"
              >
                {savingLoom ? 'Saving…' : (p.loom_url ? 'Edit Loom' : 'Add Loom')}
              </button>
              <button onClick={(e) => { e.stopPropagation(); onDelete(p.id); }} className="btn-danger text-xs px-3 py-1">
                Delete Proposal
              </button>
            </div>
          </td>
        </tr>
      )}
    </>
  );
});
