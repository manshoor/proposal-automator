export default function Sidebar() {
  const pathname = usePathname();
  const [userEmail, setUserEmail] = useState('');

  useEffect(() => {
    if (typeof window !== 'undefined') {
      // Decode JWT to get email
      const token = localStorage.getItem('accessToken');
      if (token) {
        try {
          const payload = JSON.parse(atob(token.split('.')[1]));
          setUserEmail(payload.email || '');
        } catch { /* ignore */ }
      }
    }
  }, []);

  return (
    <aside className="fixed left-0 top-0 w-64 min-h-screen bg-gradient-to-b from-gray-900 via-gray-900 to-gray-950 text-white flex flex-col">
      {/* Brand */}
      <div className="px-5 py-5">
        <h1 className="text-lg font-bold tracking-tight">Proposal Automator</h1>
        <p className="text-xs text-gray-500 mt-0.5">Upwork Dashboard</p>
        <div className="mt-3 h-0.5 bg-gradient-to-r from-blue-500 to-blue-600 rounded-full" />
      </div>

      {/* Navigation */}
      <nav className="flex-1 py-2 px-3">
        {NAV.map((item) => {
          const active = pathname === item.href || pathname.startsWith(item.href + '/');
          return (
            <Link
              key={item.href}
              href={item.href}
              className={`flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm transition-all duration-150 mb-0.5 ${
                active
                  ? 'bg-blue-600/20 text-blue-400 font-medium border-l-2 border-blue-500 ml-0 pl-2.5'
                  : 'text-gray-400 hover:text-white hover:bg-white/5 border-l-2 border-transparent'
              }`}
            >
              <span className={active ? 'text-blue-400' : 'text-gray-500'}>{item.icon}</span>
              {item.label}
            </Link>
          );
        })}
      </nav>

      {/* User + Logout */}
      <div className="px-4 py-4 border-t border-gray-800/50">
        {userEmail && (
          <div className="text-xs text-gray-500 truncate mb-2" title={userEmail}>
            {userEmail}
          </div>
        )}
        <button
          onClick={() => {
            localStorage.removeItem('accessToken');
            localStorage.removeItem('refreshToken');
            window.location.href = '/login';
          }}
          className="flex items-center gap-2 text-sm text-gray-500 hover:text-white transition-colors w-full"
        >
          <svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round"><path d="M9 21H5a2 2 0 0 1-2-2V5a2 2 0 0 1 2-2h4"/><polyline points="16 17 21 12 16 7"/><line x1="21" y1="12" x2="9" y2="12"/></svg>
          Logout
        </button>
        <div className="mt-3 flex items-center gap-2">
          <span className="text-[10px] text-gray-600 bg-gray-800/50 px-2 py-0.5 rounded-full">v2.0.0</span>
        </div>
      </div>
    </aside>
  );
}
